"""Generate every ngspice netlist of the stage, run both references and write reference_<model>.json.

  model 'koren' : Koren 12AX7 'NEW MODEL' (models/12ax7_koren.lib, fetched)  -> reference (i)
  model 'dz'    : Dempwolf-Zoelzer subckt with the DK model's params (models_dz/dz_12ax7.inc) -> (ii)
Analyses: 'main'  = .op; .ac 1 Hz-100 kHz (AC_GRID, plus the band edges AC_EDGES_HZ); 1 kHz sines at 0.05/0.5/2/8 V peak for 500 ms (analysed 400-500 ms);
          'burst' = 4 V 1 kHz tone burst 10-30 ms, 120 ms.

Single source of truth (#4): netlist() builds every netlist from dk/circuit.VALUES (component values), ELEMENTS
(topology, the same as circuit.netlist()), SOLVER (options and time step) and NGBEHAVIOR (.spiceinit). Only the
valve line (.include and subckt name) differs between the models. spice/stage_12ax7.cir is the koren 'main'
netlist, written by --write-netlist for reading or running by hand and marked GENERATED.
spice/tests/test_netlists.py parses the generated netlists and fails if they diverge from VALUES or SOLVER.

Solver settings are the SOLVER constant below (tight, #5); each reference JSON records them, the ngspice
version and the analysis parameters under "generator". The ngspice binary is $NGSPICE, default
<prototypes/fullstage>/.ngenv/bin/ngspice (the conda-forge ngspice=41 env from spice/README.md).
Usage: python spice/run_refs.py [koren] [dz]      (both if none given; ~2 min each, run in parallel)
       python spice/run_refs.py --write-netlist   (rewrites spice/stage_12ax7.cir only; no ngspice needed)
"""
import json, os, subprocess, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from analysis import load_wrdata, resample_uniform, harmonics, thd, db_rel, cycle_mean, recovery_tau
from dk.circuit import VALUES

NGSPICE = os.environ.get("NGSPICE", os.path.join(HERE, "..", ".ngenv", "bin", "ngspice"))
MODELS = {"koren": (".include models/12ax7_koren.lib", "12AX7"),
          "dz": (".include models_dz/dz_12ax7.inc", "DZ12AX7")}
ANALYSES = ["main", "burst"]
AMPS = ["0.05", "0.5", "2", "8"]
# ngspice solver settings (#5). The first references used reltol 1e-4, vntol 1e-7, a 2 us max step: their
# harmonics near -100 dBc were only good to ~0.1 dB, so they could not support 0.1 dB limits. These are
# 100x tighter in reltol and 4x finer in time. Convergence check (spice/RESULTS.md, v3): 10x tighter tolerances
# and a 0.25 us step move no harmonic above -90 dBc by more than 2e-4 dB, the op point not at all and the burst
# metrics by < 3e-7 relative. Trapezoidal integration is ngspice's default.
SOLVER = dict(reltol=1e-6, abstol=1e-14, vntol=1e-9, chgtol=1e-16, method="trap", tstep=0.5e-6, tmax=0.5e-6)
NGBEHAVIOR = "psa"     # .spiceinit: PSpice compatibility, needed for Koren's PWRS() and B-source syntax
SINE = dict(f0=1e3, t_stop=0.5, t_save=0.3, fs_resample=1e6, ncycles=100)   # analysed: last 100 cycles
BURST = dict(amp=4.0, t_on=10e-3, t_off=30e-3, t_stop=0.12)
AC_GRID = dict(points_per_decade=50, f_start=1.0, f_stop=100e3)
# Exact edges of the 20 Hz-20 kHz small-signal criterion (#38): the 50/decade grid's in-band points run from
# 20.9 Hz to 19.95 kHz, so the band edge, where the warping error peaks, was never evaluated. Merged into "ac".
AC_EDGES_HZ = (20.0, 20000.0)
NETLIST_FILE = os.path.join(HERE, "stage_12ax7.cir")      # committed copy of netlist("koren", "main")

# Passive elements in netlist order: (SPICE name = circuit.VALUES key, node+, node-). Same topology as
# dk/circuit.netlist(); the valve sits between Rgs and Ra as XV1 (plate grid cathode), its inter-electrode
# capacitances (VALUES CCG/CGP/CCP) are inside the subckt.
ELEMENTS = [("Rs", "src", "in1"), ("Cin", "in1", "gl"), ("Rg", "gl", "0"), ("Rgs", "gl", "g"),
            ("Ra", "ht", "a"), ("Rk", "k", "0"), ("Ck", "k", "0"), ("Cout", "a", "out"), ("Rl", "out", "0")]
VALVE_AFTER = "Rgs"
HEADER = """* GENERATED by spice/run_refs.py ({model}, {analysis}) -- do not edit; change dk/circuit.VALUES or
* run_refs.SOLVER and run `python spice/run_refs.py --write-netlist`. spice/tests/test_netlists.py checks it.
* One-stage 12AX7 common-cathode stage. Component values: dk/circuit.VALUES (example values, NOT Culture
* Vulture values; sources in dk/circuit.py).
* Valve: {valve}.
* Solver: {solver}.
* .spiceinit sets ngbehavior={ngbehavior}.
"""
VALVES = {"koren": "Norman Koren \"12AX7 NEW MODEL\" (fetched by models/fetch_models.sh, not redistributed)",
          "dz": "Dempwolf-Zoelzer behavioural subckt with the DK model's params (models_dz/dz_12ax7.inc)"}
_PREFIXES = [(1e6, "Meg"), (1e3, "k"), (1.0, ""), (1e-3, "m"), (1e-6, "u"), (1e-9, "n"), (1e-12, "p")]


def spice_num(x):
    """x in SPICE engineering notation, e.g. 22e-9 -> '22n', 1e6 -> '1Meg', 300 -> '300' (12 significant digits)."""
    if x == 0:
        return "0"
    scale, suffix = next(((s, p) for s, p in _PREFIXES if abs(x) >= s * (1 - 1e-12)), _PREFIXES[-1])
    return f"{x / scale:.12g}{suffix}"


def netlist(model, analysis, out="out", values=VALUES, solver=SOLVER):
    """The complete ngspice netlist (text) of `analysis` ('main' or 'burst') for `model`; wrdata goes to `out`/."""
    inc, sub = MODELS[model]
    ts, tm = f"{solver['tstep']:g}", f"{solver['tmax']:g}"
    f0 = f"{SINE['f0']:g}"
    if analysis == "main":
        vin = f"Vin src 0 DC 0 AC 1 SIN(0 {AMPS[0]} {f0})"
        g = AC_GRID
        edges = "".join(f"ac lin 1 {spice_num(fe)} {spice_num(fe)}\n"
                        f"wrdata {out}/{model}_ac_{fe:g}.txt db(v(out)) ph(v(out))\n" for fe in AC_EDGES_HZ)
        control = f"""op
let ia = -i(VHT)
wrdata {out}/{model}_op.txt v(a) v(k) v(g) v(gl) ia
ac dec {g['points_per_decade']} {spice_num(g['f_start'])} {spice_num(g['f_stop'])}
wrdata {out}/{model}_ac.txt db(v(out)) ph(v(out))
{edges}foreach A {' '.join(AMPS)}
  alter @Vin[sin] = [ 0 $A {f0} ]
  tran {ts} {SINE['t_stop']:g} {SINE['t_save']:g} {tm}
  set fn = {out}/{model}_sine_{{$A}}.txt
  wrdata $fn v(out) v(g) v(k)
end"""
    elif analysis == "burst":
        b = BURST
        vin = f"Bin src 0 V = {b['amp']:g}*sin(2*3.14159265*{f0}*time)*((time>{b['t_on']:g})&(time<{b['t_off']:g}))"
        control = f"""tran {ts} {b['t_stop']:g} 0 {tm}
wrdata {out}/{model}_burst.txt v(g) v(k) v(out) v(gl)"""
    else:
        raise ValueError(f"unknown analysis {analysis!r}")
    lines = [inc, f"VHT ht 0 DC {spice_num(values['HT'])}", vin]
    for name, p, q in ELEMENTS:
        lines.append(f"{name:<3} {p} {q} {spice_num(values[name])}")
        if name == VALVE_AFTER:
            lines.append(f"XV1 a g k {sub}")
    lines.append(" ".join([".options"] + [f"{k}={solver[k]:g}" for k in ("reltol", "abstol", "vntol", "chgtol")]
                          + [f"method={solver['method']}"]))
    hdr = HEADER.format(model=model, analysis=analysis, valve=VALVES[model], ngbehavior=NGBEHAVIOR,
                        solver=", ".join(f"{k}={v:g}" if isinstance(v, float) else f"{k}={v}"
                                         for k, v in solver.items()))
    return hdr + "\n".join(lines) + "\n\n.control\n" + control + "\n.endc\n.end\n"


def spiceinit():
    """The .spiceinit ngspice reads from spice/; must match NGBEHAVIOR (checked, not rewritten)."""
    txt = open(os.path.join(HERE, ".spiceinit")).read().strip()
    if txt != f"set ngbehavior={NGBEHAVIOR}":
        raise RuntimeError(f"spice/.spiceinit is {txt!r}, expected 'set ngbehavior={NGBEHAVIOR}'")
    return txt


def write_netlist(fn=NETLIST_FILE):
    open(fn, "w").write(netlist("koren", "main"))
    return fn


def ngspice_version():
    r = subprocess.run([NGSPICE, "--version"], capture_output=True, text=True)
    return next((ln.strip("* ").split(":")[0].strip() for ln in r.stdout.splitlines() if "ngspice-" in ln), r.stdout.strip())


def run(model, solver=SOLVER, out="out", write=True):
    """Simulate `model` with `solver` settings into spice/<out>/ and analyse it; write=True (re)writes
    the committed reference_<model>.json, write=False is for convergence studies."""
    o = os.path.join(HERE, out)
    os.makedirs(o, exist_ok=True)
    init = spiceinit()
    for name in ANALYSES:
        fn = os.path.join(HERE, f"_gen_{out.replace('/', '_')}_{model}_{name}.cir")
        open(fn, "w").write(netlist(model, name, out=out, solver=solver))
        r = subprocess.run([NGSPICE, "-b", fn], cwd=HERE, capture_output=True, text=True)
        open(os.path.join(o, f"{model}_{name}_log.txt"), "w").write(r.stdout + r.stderr)
        os.remove(fn)
        if r.returncode != 0:
            raise RuntimeError(f"ngspice failed on {name} ({model}), see {o}/{model}_{name}_log.txt")
    gen = dict(script="spice/run_refs.py", ngspice=ngspice_version(), solver=solver, sine=SINE, burst=BURST,
               ac=dict(AC_GRID, edges_hz=AC_EDGES_HZ), spiceinit=init)
    return analyse(model, out, gen, write)


def analyse(model, out="out", generator=None, write=True):
    o = os.path.join(HERE, out)
    op = np.loadtxt(os.path.join(o, f"{model}_op.txt"))   # (scale, value) pairs, no header
    va, vk, vg, vgl, ia = op[1], op[3], op[5], op[7], op[9]
    ac = np.vstack([np.loadtxt(os.path.join(o, fn), ndmin=2) for fn in
                    [f"{model}_ac.txt"] + [f"{model}_ac_{fe:g}.txt" for fe in AC_EDGES_HZ]])
    ac = ac[np.argsort(ac[:, 0], kind="stable")]
    res = dict(model=model, generator=generator, op=dict(va=va, vk=vk, vg=vg, vgl=vgl, ia=ia, vgk=vg - vk),
               ac=dict(f=ac[:, 0].tolist(), db=ac[:, 1].tolist()), sine={})
    for a in AMPS:
        t, v = load_wrdata(os.path.join(o, f"{model}_sine_{a}.txt"), 3)
        _, y = resample_uniform(t, v[:, 0], SINE["fs_resample"], SINE["t_save"], SINE["t_stop"])
        h = harmonics(y, SINE["fs_resample"], SINE["f0"], SINE["ncycles"])
        res["sine"][a] = dict(H_peak_V=h[:5].tolist(), H_dBc=db_rel(h)[:5].tolist(), thd_pct=100 * thd(h))
    t, v = load_wrdata(os.path.join(o, f"{model}_burst.txt"), 4)
    tu, g = resample_uniform(t, v[:, 0], 1e6, 0.0, BURST["t_stop"])
    _, k = resample_uniform(t, v[:, 1], 1e6, 0.0, BURST["t_stop"])
    res["burst"] = burst_metrics(tu, g - k)
    if write:   # committed reference data
        json.dump(res, open(os.path.join(HERE, f"reference_{model}.json"), "w"), indent=1)
    return res


def burst_metrics(t, vgk, f0=1e3):
    fs = 1.0 / (t[1] - t[0])
    b = cycle_mean(vgk, fs, f0)
    rest = float(np.mean(b[(t > 2e-3) & (t < 9e-3)]))
    m = (t > 10.5e-3) & (t < 119e-3)
    i = np.argmin(b[m])
    tau = recovery_tau(t, b, 30.5e-3, rest)
    tg = np.arange(0.0, 0.119, 0.5e-3)          # trajectory on a 0.5 ms grid for shape comparison
    return dict(rest_vgk=rest, min_vgk=float(b[m][i]), t_min=float(t[m][i]), recovery_tau_s=tau,
                traj_t=tg.tolist(), traj_vgk=np.interp(tg, t, b).tolist())


if __name__ == "__main__":
    if sys.argv[1:] == ["--write-netlist"]:
        print("wrote", write_netlist())
        sys.exit(0)
    for mdl in sys.argv[1:] or list(MODELS):
        r = run(mdl)
        print(mdl, r["op"], {a: round(s["thd_pct"], 3) for a, s in r["sine"].items()},
              {k: r["burst"][k] for k in ("rest_vgk", "min_vgk", "t_min", "recovery_tau_s")})
