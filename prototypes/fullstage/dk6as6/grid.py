"""The g1 grid current (#112): what it does to the 6AS6 stage, against the stage without it and against ngspice.

The grid law (dk6as6/pentode.py, grid()) is Dempwolf & Zoelzer's 12AX7 grid current (DAFx-11 eq. (11), RSD-1 shape)
scaled by the fitted cathode-perveance ratio: BORROWED, NOT 6AS6 DATA (no 6AS6 / 5725 sheet has grid-current curves).
Everything here compares the same-model DK stage and ngspice reference (method checks) and the stage with and without
the borrowed law (its effect); nothing here validates the law against a valve.

  "static"   Ig1, Ip, Ig2 vs Vg1k (-3 ... +2 V, 50 mV steps) at fixed (Vg2k, Vg3k, Vak): P1-like (120, 0, 150 V) and
             T-like (50, 50, 50 V): the DK law (pentode.currents_grid) against ngspice's .dc of the dualg subckt
             (spice6as6/models/6as6_dualg.inc), which should agree to ngspice's own arithmetic.
  "burst"    the 4 V 1 kHz burst per mode / bias, with (dualg) and without (dual) grid current, DK (standard) and
             ngspice: rest Vgk, the shift (min - rest), the grid DC (cycle-mean Vgk) at the burst's end (30 ms) and at
             35 / 50 / 119 ms, CRIT's recovery tau and the tail-fit tau (31-118 ms); read from results[_grid][_T].json
             and the references, so no extra simulation.
  "thd"      THD and H2-H5 vs drive at spice/run_refs.AMPS with and without grid current (DK standard and ngspice),
             from the same files.
  "hf"       steady state across the band: T at HF_BIASES x HF_DRIVES x HF_TONES (0.4 s from silence), the same limits
             plus Newton convergence: where T's supported envelope ends with grid current.
  "envelope" the DK stage (standard 8x) with grid current at ENV_BIASES x ENV_DRIVES (1 kHz, last 100 cycles of a
             0.5 s sine), and the tone onsets of PR #121's review (an 8 V zero-phase sine from silence at 1037-19037 Hz,
             the first 30 ms): max Vg1k, min Vak, min Ip + Ig2 (= Ik - Ig1), max Ig1, Newton. The law's limits: the
             plate above the cathode and Ip + Ig2 > 0 (stage.py, the supported envelope).
Run: python -m dk6as6.grid [static] [envelope] [hf] [tables] [--workers N]   (from prototypes/fullstage; all if none
     given)
     -> dk6as6/grid.json (each of static / envelope / hf replaces its own key). "static" needs ngspice ($NGSPICE).
     "tables" prints the burst / THD tables of RESULTS.md (not stored: they are derived from the committed
     results[_grid][_T].json and references; PR #128 review); it needs those files.
"""
