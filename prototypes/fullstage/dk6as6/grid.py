from analysis import harmonics, thd  # noqa: E402 -- after the sys.path setup
from dk.validate import aligned  # noqa: E402 -- after the sys.path setup
from spice.run_refs import AMPS  # noqa: E402 -- after the sys.path setup
from dk6as6 import pentode  # noqa: E402 -- after the sys.path setup
from dk6as6.stage import Stage, supported, SUPPORTED_MA  # noqa: E402 -- after the sys.path setup
from dk6as6 import modes, validate as V  # noqa: E402 -- after the sys.path setup
from spice6as6 import run_refs as R  # noqa: E402 -- after the sys.path setup

FS = 48000.0
JSON = os.path.join(HERE, "grid.json")
STATIC_VG1 = np.round(np.arange(-3.0, 2.0 + 1e-9, 0.05), 10)
STATIC_POINTS = {"P1": (120.0, 0.0, 150.0), "T": (50.0, 50.0, 50.0)}    # (Vg2k, Vg3k, Vak)
ENV_MODES = ("P1", "T")
ENV_BIASES = {"P1": (0.1, 0.25, 0.45, 0.6), "T": modes.BIASES}   # T at every 50 uA: where the grid current matters
ENV_DRIVES = (2.0, 4.0, 6.0, 8.0)                                  # V peak; below 2 V g1 stays below -1.4 V in T
ONSET_TONES = (1037.0, 5037.0, 10037.0, 15037.0, 18037.0, 19037.0)      # Hz, 8 V peak, zero phase, from silence
ONSET_S = 0.03
# Steady state across the band (#112: before the Newton restart, T at 0.6 mA lost Newton on a steady 8 V, 15 kHz tone
# though 1 kHz and every onset converged): tones every 2 kHz, 0.4 s from silence, at T's upper currents
HF_BIASES = (0.35, 0.4, 0.45, 0.5, 0.55, 0.6)
HF_DRIVES = (4.0, 6.0, 8.0)
HF_TONES = tuple(1037.0 + 2000.0 * k for k in range(10))           # 1037 ... 19037 Hz
HF_S = 0.4
# grid DC read-outs: the burst's end and the research note's 35 / 50 / 119 ms, the last at the trajectory's last
# full-window sample, 118.5 ms (PR #128 review: np.interp clamped "119 ms" to it)
TRAJ_MS = (30.0, 35.0, 50.0, 118.5)


# --- static Ig-Vgk sweep ------------------------------------------------------------------------------------

def static_netlist(point, out):
    vg2, vg3, va = point
    inc, sub = R.models("dualg", "P1")
    return f"""* GENERATED by dk6as6/grid.py: static Ig1 / Ip / Ig2 vs Vg1k of the dualg subckt (#112)
{inc}
VG1 g1 0 DC 0
VG2 g2 0 DC {vg2:g}
VG3 g3 0 DC {vg3:g}
VA a 0 DC {va:g}
XV1 a g2 g3 g1 0 {sub}
.options {' '.join(f'{k}={R.SOLVER[k]:g}' for k in ('reltol', 'abstol', 'vntol', 'chgtol'))}
.control
set numdgt=16
dc VG1 {STATIC_VG1[0]:g} {STATIC_VG1[-1]:g} 0.05
let ig1 = -i(VG1)
let ip = -i(VA)
let ig2 = -i(VG2)
wrdata {out} ig1 ip ig2
.endc
.end
"""


def static():
    out = {}
    os.makedirs(os.path.join(R.HERE, "out"), exist_ok=True)
    for name, point in STATIC_POINTS.items():
        fn = os.path.join(R.HERE, f"_gen_grid_static_{name}.cir")
        dat = f"out/grid_static_{name}.txt"
        open(fn, "w").write(static_netlist(point, dat))
        try:
            code, log = R.ngspice(["-b", os.path.basename(fn)], timeout=600)
        finally:
            os.remove(fn)
        if code != 0:
            raise RuntimeError(f"ngspice static sweep failed: {log[-2000:]}")
        d = np.loadtxt(os.path.join(R.HERE, dat))
        vg1, sp = d[:, 0], {"ig1": d[:, 1], "ip": d[:, 3], "ig2": d[:, 5]}
        dk = np.array([pentode.currents_grid(v, *point)[:3] for v in vg1])
        rows = []
        for j, v in enumerate(vg1):
            ip0, ig20, _ = pentode.currents(v, *point)
            ig1 = dk[j, 2]
            rows.append(dict(vg1k=float(v), ig1_dk=ig1, ig1_spice=float(sp["ig1"][j]), ip_dk=dk[j, 0],
                             ip_spice=float(sp["ip"][j]), ig2_dk=dk[j, 1], ig2_spice=float(sp["ig2"][j]),
                             ik=ip0 + ig20))
        def worst(key, scale):
            return max(abs(r[f"{key}_dk"] - r[f"{key}_spice"]) / scale(r) for r in rows if scale(r) > 0)
        out[name] = dict(
            vg2k=point[0], vg3k=point[1], vak=point[2], rows=rows,
            # Ig1 relative to itself where it is above 1e-15 A (below, ngspice's ln(1+exp(-|x|)) and abstol rule);
            # Ip, Ig2 relative to the cathode current (they are differences Ik f - Ig1 f)
            ig1_worst_rel=max(abs(r["ig1_dk"] / r["ig1_spice"] - 1) for r in rows if r["ig1_dk"] > 1e-15),
            ip_worst_rel_ik=worst("ip", lambda r: r["ik"] + r["ig1_dk"]),
            ig2_worst_rel_ik=worst("ig2", lambda r: r["ik"] + r["ig1_dk"]),
            # ngspice solves the source currents to its Newton tolerance, reltol |I| + abstol: <= 1 means agreement
            # to ngspice's own convergence
            worst_re_ngspice_tol=max(abs(r[f"{k}_dk"] - r[f"{k}_spice"]) / (R.SOLVER["reltol"] * abs(r[f"{k}_spice"])
                                                                            + R.SOLVER["abstol"])
                                     for r in rows for k in ("ig1", "ip", "ig2")),
            ngspice=R.ngspice_version())
    return out


# --- the envelope: swings with grid current --------------------------------------------------------------------

def _tone(a):
    mode, bias, drive = a
    warnings.simplefilter("ignore")
    st = Stage(FS, bias=bias, mode=mode, experimental=True)
    t = np.arange(int(modes.T * FS) + st.latency_samples) / FS
    r = aligned(st, drive * np.sin(2 * np.pi * 1000 * t), record=("out", "vgk", "vak", "ig1", "ipk"))
    i = r["_internal"]
    n = len(i["vgk"])
    keep = slice(n - int(100 * st.fs / 1000.0), n)
    h = harmonics(r["out"], FS, 1000.0, 100)
    s = st.iteration_stats()
    return dict(mode=mode, bias_ma=bias, drive=drive, supported=st.supported, vg1k_max=float(i["vgk"][keep].max()),
                vak_min=float(i["vak"][keep].min()), ipk_min=float(i["ipk"][keep].min()),
                ig1_max=float(i["ig1"][keep].max()), H1_V_peak=float(h[0]), thd_pct=100 * thd(h),
                nonconverged=s["nonconverged"], it_max=s["max"], restarted=st.restarted, it_mean=s["mean"])


def _onset(a):
    mode, bias, f0, quality = a
    warnings.simplefilter("ignore")
    st = Stage(FS, bias=bias, mode=mode, quality=quality, experimental=True)
    t = np.arange(int(ONSET_S * FS) + st.latency_samples) / FS
    r = st.process(8.0 * np.sin(2 * np.pi * f0 * t), record=("out", "vgk", "vak", "ig1", "ipk"))["_internal"]
    s = st.iteration_stats()
    return dict(mode=mode, bias_ma=bias, f_hz=f0, quality=quality, supported=st.supported,
                vg1k_max=float(r["vgk"].max()), vak_min=float(r["vak"].min()), ipk_min=float(r["ipk"].min()),
                ig1_max=float(r["ig1"].max()), nonconverged=s["nonconverged"], it_max=s["max"], restarted=st.restarted)


def _hf(a):
    mode, bias, drive, f0 = a
    warnings.simplefilter("ignore")
    st = Stage(FS, bias=bias, mode=mode, experimental=True)
    t = np.arange(int(HF_S * FS) + st.latency_samples) / FS
    r = st.process(drive * np.sin(2 * np.pi * f0 * t), record=("out", "vgk", "vak", "ig1", "ipk"))["_internal"]
    s = st.iteration_stats()
    return dict(mode=mode, bias_ma=bias, drive=drive, f_hz=f0, supported=st.supported,
                vg1k_max=float(r["vgk"].max()), vak_min=float(r["vak"].min()), ipk_min=float(r["ipk"].min()),
                ig1_max=float(r["ig1"].max()), nonconverged=s["nonconverged"], it_max=s["max"], restarted=st.restarted)


def hf(workers=None):
    jobs = [("T", b, d, f) for b in HF_BIASES for d in HF_DRIVES for f in HF_TONES]
    with ProcessPoolExecutor(workers) as ex:
        out = list(ex.map(_hf, jobs))
    for r in out:
        r["in_law"] = in_law(r) and r["nonconverged"] == 0
    return dict(rows=out, biases=HF_BIASES, drives=HF_DRIVES, tones=HF_TONES, seconds=HF_S)


def in_law(r):
    """The grid-current law's limits (stage.py): the plate above the cathode and Ip + Ig2 > 0."""
    return r["vak_min"] > 0.0 and r["ipk_min"] > 0.0


def envelope(workers=None):
    tones = [(m, b, d) for m in ENV_MODES for b in ENV_BIASES[m] for d in ENV_DRIVES]
    onsets = [(m, b, f, q) for m in ENV_MODES for b in ENV_BIASES[m] if supported(m, b) for f in ONSET_TONES
              for q in ("standard", "hq")]
    with ProcessPoolExecutor(workers) as ex:
        t = list(ex.map(_tone, tones))
        o = list(ex.map(_onset, onsets))
    for r in t + o:
        r["in_law"] = in_law(r)
    return dict(tones=t, onsets=o, supported_ma=SUPPORTED_MA)


# --- burst and THD tables from the committed validation and references -------------------------------------------

def _burst_row(b):
    """Grid DC (cycle-mean Vgk) read-outs and the decay constants of one burst_metrics dict."""
    t, v = np.array(b["traj_t"]), np.array(b["traj_vgk"])
    row = dict(rest_vgk=b["rest_vgk"], shift_v=b["min_vgk"] - b["rest_vgk"], t_min_ms=1e3 * b["t_min"],
               recovery_tau_s=b["recovery_tau_s"])
    for ms in TRAJ_MS:
        row[f"vgk_{ms:g}ms"] = float(np.interp(ms * 1e-3, t, v))
    row["tail_tau_s"] = V.tail_tau(b)
    return row


def tables():
    burst, thds = [], []
    for mode in ENV_MODES:
        res = {m: json.load(open(V.results_file(mode, m))) for m in ("dual", "dualg")}
        for b in R.GRID_BIASES[mode]:
            key = f"{b:g}"
            row = dict(mode=mode, bias_ma=b, supported=supported(mode, b), supported_no_grid=supported(mode, b, 0.0))
            for m, tag in (("dual", "no_grid"), ("dualg", "grid")):
                if key not in res[m]:           # T 0.5 mA: a grid reference only (the top of T's grid envelope)
                    row[tag] = None
                    continue
                dk = res[m][key]["standard"]
                ref = V.ref(m, b, mode)
                row[tag] = dict(dk=_burst_row(dk["burst"]), spice=_burst_row(ref["burst"]),
                                status=V.status(dk), passed=dk["passed"],
                                **({"spice_exp_capped": True} if dk["burst"].get("spice_exp_capped") else {}))
            burst.append(row)
            for a in AMPS:
                tr = dict(mode=mode, bias_ma=b, drive=float(a))
                for m, tag in (("dual", "no_grid"), ("dualg", "grid")):
                    if key not in res[m]:
                        tr[tag] = None
                        continue
                    dk, ref = res[m][key]["standard"]["sine"][a], V.ref(m, b, mode)["sine"][a]
                    tr[tag] = dict(thd_dk_pct=dk["thd_pct"], thd_spice_pct=ref["thd_pct"], H_dBc_dk=dk["H_dBc"][1:5],
                                   H_dBc_spice=ref["H_dBc"][1:5], H1_dk=dk["H_peak_V"][0],
                                   **({"spice_exp_capped": True} if dk.get("spice_exp_capped") else {}))
                thds.append(tr)
    return dict(burst=burst, thd=thds)


